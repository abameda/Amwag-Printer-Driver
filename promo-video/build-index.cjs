// Writes composition/index.html (English) and generates the Arabic project composition-ar/ from the same scenes,
// sound list and assets, so both versions always share the same timing. Edit the scenes in composition/ only, then
// run: node build-index.cjs
const fs = require("fs");
const path = require("path");

const scenes = [
  ["intro", 0, 6.4],
  ["open", 6.4, 5.4],
  ["app", 11.8, 39.0],
  ["outro", 50.8, 8.9],
];
// [root time in seconds, file in assets/sfx, volume] — each sound sits on a visible action.
const sfx = [
  [8.15, "click-a", 0.9], [8.3, "click-b", 0.9], [11.45, "slide-b", 0.5],                 // double-click exe, zoom into app
  [14.0, "pop-a", 0.45], [15.6, "pop-b", 0.45], [23.4, "click-a", 0.9],                   // steps 1-2 done, Yes
  [24.8, "pop-c", 0.45], [26.2, "pop-a", 0.45], [27.4, "pop-b", 0.45], [28.0, "pop-c", 0.45], [28.25, "bell", 0.3], // steps 3-6 done, Ready
  [32.4, "click-b", 0.9], [34.4, "click-a", 0.9], [36.5, "slide-a", 0.55],                // Print Test Ticket, Print, ticket feeds out
  [38.4, "pop-a", 0.45], [39.3, "pop-b", 0.45], [40.2, "pop-c", 0.45], [41.1, "pop-a", 0.45], // four ticket checks
  [42.7, "click-b", 0.9], [44.4, "click-a", 0.9],                                          // Printed correctly, Check ticket software
  [47.4, "pop-b", 0.4], [47.9, "pop-c", 0.4], [48.4, "pop-a", 0.4], [48.9, "pop-b", 0.4], // table rows match
  [50.25, "slide-b", 0.5], [51.7, "pop-c", 0.45], [52.3, "pop-a", 0.45],                  // window leaves, help chips
  [54.7, "slide-a", 0.35], [57.05, "slide-b", 0.3],                                         // logo assembles, name sweep
];
// Music: a custom ElevenLabs Music v2.5 instrumental (60 s, generated for this video via Higgsfield). Starting it
// 0.2 s in lands its full-band entrance (18.3 s in the file) on "When Windows asks, choose Yes" at 18.1 s.
const TOTAL = 59.7;

function build(lang) {
  const hosts = scenes.map(([id, start, dur]) =>
`      <div id="${id}" class="clip" data-composition-id="${id}" data-composition-src="compositions/${id}.html"
           data-variable-values='{"lang":"${lang}"}'
           data-start="${start}" data-duration="${dur}" data-track-index="1" data-track-kind="graphics" data-width="1920" data-height="1080"></div>`).join("\n");
  const fx = sfx.map(([t, name, vol], i) =>
`      <audio id="sfx-${String(i + 1).padStart(2, "0")}" class="clip" src="assets/sfx/${name}.ogg" data-start="${t}" data-track-index="3" data-volume="${vol}"></audio>`).join("\n");
  return `<!doctype html>
<!-- Generated by ../build-index.cjs: edit that file, not this one. -->
<html lang="${lang}"${lang === "ar" ? ' dir="rtl"' : ""}>
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; width: 1920px; height: 1080px; overflow: hidden; background: #0f2a4a; }
      #root { position: relative; width: 100%; height: 100%; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${TOTAL}" data-width="1920" data-height="1080">
${hosts}
      <audio id="music-bed" class="clip" src="assets/music/amwag-custom-bed.mp3" data-start="0" data-duration="${TOTAL}" data-media-start="0.2" data-track-index="2" data-volume="0.55" data-fade-in="0.2" data-fade-out="0.5"></audio>
${fx}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;
}

const en = path.join(__dirname, "composition");
const ar = path.join(__dirname, "composition-ar");
fs.writeFileSync(path.join(en, "index.html"), build("en"));

// The Arabic project: a generated copy (one root composition per project), same scenes with lang = "ar".
fs.mkdirSync(ar, { recursive: true });
for (const item of ["compositions", "assets", "hyperframes.json", "package.json", "CLAUDE.md", "AGENTS.md"]) {
  fs.rmSync(path.join(ar, item), { recursive: true, force: true });
  fs.cpSync(path.join(en, item), path.join(ar, item), { recursive: true });
}
fs.writeFileSync(path.join(ar, "meta.json"), JSON.stringify({ id: "composition-ar", name: "AMWAG Printer Setup (Arabic)" }, null, 2) + "\n");
fs.writeFileSync(path.join(ar, "index.html"), build("ar").replace("<!-- Generated by ../build-index.cjs: edit that file, not this one. -->",
  "<!-- Generated by ../build-index.cjs from ../composition: do not edit anything in this folder. -->"));
console.log("Wrote composition/index.html and generated composition-ar/");
